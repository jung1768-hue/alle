export function resolveBundledImage(imageUrl?: string): string | undefined {
  if (!imageUrl) return imageUrl;
  for (const [assetKey, bundledSrc] of BUNDLED_IMAGE_ENTRIES) {
    if (imageUrl.includes(assetKey)) {
      return bundledSrc;
    }
  }
  return imageUrl;
}

export function resolveFallbackFoodImage(label: string): string {
  const lower = label.toLowerCase();
  for (const entry of CATEGORY_FALLBACK_IMAGES) {
    if (entry.keywords.some((kw) => lower.includes(kw))) {
      return entry.image;
    }
  }
  return IMG_HAEJANG;
}

